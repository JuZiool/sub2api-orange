const columnKeys = (wrapper: ReturnType<typeof mount>) =>
  wrapper.get('[data-test="columns"]').text().split(',').filter(Boolean)

const openColumnSettings = async (wrapper: ReturnType<typeof mount>) => {
  await wrapper.get('button[title="Column Settings"]').trigger('click')
}

const clickColumnToggle = async (wrapper: ReturnType<typeof mount>, label: string) => {
  const button = wrapper
    .findAll('button')
    .find((item) => item.text().includes(label))
  expect(button, `column toggle ${label}`).toBeTruthy()
  await button!.trigger('click')
  await flushPromises()
}

describe('admin GroupsView column settings', () => {
  beforeEach(() => {
    localStorage.clear()

    listGroups.mockReset()
    getAllGroups.mockReset()
    getModelAllowlistCandidates.mockReset()
    getUsageSummary.mockReset()
    getCapacitySummary.mockReset()
    getGroupProfits.mockReset()
    getLiveCapability.mockReset()
    listAccounts.mockReset()
    showError.mockReset()
    showSuccess.mockReset()
    isCurrentStep.mockReset()
    nextStep.mockReset()
    authState.isSimpleMode = false

    listGroups.mockResolvedValue({
      items: [createGroup()],
      total: 1,
      page: 1,
      page_size: 20,
      pages: 1,
    })
    getAllGroups.mockResolvedValue([])
    getModelAllowlistCandidates.mockResolvedValue([])
    getUsageSummary.mockResolvedValue([])
    getCapacitySummary.mockResolvedValue([])
    getGroupProfits.mockResolvedValue({ items: [], generated_at: '', cached: false })
    getLiveCapability.mockResolvedValue({ supported: false })
    listAccounts.mockResolvedValue({ items: [], total: 0, page: 1, page_size: 20, pages: 0 })
    isCurrentStep.mockReturnValue(false)
  })

  it('does not call advanced group APIs or expose the exclusive filter in simple mode', async () => {
    authState.isSimpleMode = true
    const wrapper = await mountView()

    expect(getLiveCapability).not.toHaveBeenCalled()
    expect(getModelAllowlistCandidates).not.toHaveBeenCalled()
    expect(getUsageSummary).not.toHaveBeenCalled()
    expect(getCapacitySummary).not.toHaveBeenCalled()
    // Orange 特有：简单模式不请求利润 / 上游成本倍率接口
    expect(getGroupProfits).not.toHaveBeenCalled()
    expect(listGroups).toHaveBeenCalledWith(
      expect.any(Number),
      expect.any(Number),
      expect.objectContaining({ is_exclusive: undefined }),
      expect.anything(),
    )
    expect(wrapper.find('select').text()).not.toContain('admin.groups.allGroups')
  })

  afterEach(() => {
    localStorage.clear()
  })

  it('hides the id column by default while keeping other group columns visible', async () => {
    const wrapper = await mountView()

    expect(columnKeys(wrapper)).toEqual([
      'name',
      'platform',
      'billing_type',
      'rate_multiplier',
      'upstream_rate_multiplier',
      'is_exclusive',
      'account_count',
      'capacity',
      'usage',
      'profit',
      'status',
      'actions',
    ])
    expect(localStorage.getItem('group-hidden-columns')).toBe(JSON.stringify(['id']))
    expect(localStorage.getItem('group-column-settings-version')).toBe('2')
  })

  it('applies saved hidden columns on mount and ignores unknown keys', async () => {
    localStorage.setItem(
      'group-hidden-columns',
      JSON.stringify(['usage', 'capacity', 'removed_column', 'name', 'actions']),
    )
    localStorage.setItem('group-column-settings-version', '2')

    const wrapper = await mountView()

    expect(columnKeys(wrapper)).toEqual([
      'name',
      'id',
      'platform',
      'billing_type',
      'rate_multiplier',
      'upstream_rate_multiplier',
      'is_exclusive',
      'account_count',
      'profit',
      'status',
      'actions',
    ])
  })

  it('auto-hides id for existing saved column prefs after version bump', async () => {
    localStorage.setItem('group-hidden-columns', JSON.stringify(['usage']))
    // No version key → treated as version 1, migrate to 2 and hide id.

    const wrapper = await mountView()

    expect(columnKeys(wrapper)).toEqual([
      'name',
      'platform',
      'billing_type',
      'rate_multiplier',
      'upstream_rate_multiplier',
      'is_exclusive',
      'account_count',
      'capacity',
      'profit',
      'status',
      'actions',
    ])
    expect(JSON.parse(localStorage.getItem('group-hidden-columns')!)).toEqual(
      expect.arrayContaining(['usage', 'id']),
    )
    expect(localStorage.getItem('group-column-settings-version')).toBe('2')
  })

  it('toggles a column and persists hidden column keys', async () => {
    const wrapper = await mountView()

    await openColumnSettings(wrapper)
    await clickColumnToggle(wrapper, 'Usage')

    expect(columnKeys(wrapper)).toEqual([
      'name',
      'platform',
      'billing_type',
      'rate_multiplier',
      'upstream_rate_multiplier',
      'is_exclusive',
      'account_count',
      'capacity',
      'profit',
      'status',
      'actions',
    ])
    expect(JSON.parse(localStorage.getItem('group-hidden-columns')!)).toEqual(
      expect.arrayContaining(['id', 'usage']),
    )
  })

  it('can show the id column from column settings', async () => {
    const wrapper = await mountView()

    await openColumnSettings(wrapper)
    await clickColumnToggle(wrapper, 'ID')

    expect(columnKeys(wrapper)).toEqual([
      'name',
      'id',
      'platform',
      'billing_type',
      'rate_multiplier',
      'upstream_rate_multiplier',
      'is_exclusive',
      'account_count',
      'capacity',
      'usage',
      'profit',
      'status',
      'actions',
    ])
    expect(localStorage.getItem('group-hidden-columns')).toBe(JSON.stringify([]))
  })

  it('skips usage and capacity fetches until consuming columns are shown', async () => {
    localStorage.setItem(
      'group-hidden-columns',
      JSON.stringify(['billing_type', 'usage', 'capacity']),
    )

    const wrapper = await mountView()

    expect(getUsageSummary).not.toHaveBeenCalled()
    expect(getCapacitySummary).not.toHaveBeenCalled()

    await openColumnSettings(wrapper)
    await clickColumnToggle(wrapper, 'Usage')
    expect(getUsageSummary).toHaveBeenCalledTimes(1)
    expect(getUsageSummary).toHaveBeenCalledWith()
    expect(getCapacitySummary).not.toHaveBeenCalled()

    await clickColumnToggle(wrapper, 'Capacity')
    expect(getUsageSummary).toHaveBeenCalledTimes(1)
    expect(getCapacitySummary).toHaveBeenCalledTimes(1)
  })

  it('renders yesterday usage between today and total', async () => {
    getUsageSummary.mockResolvedValue([
      { group_id: 1, today_cost: 1.25, yesterday_cost: 2.5, total_cost: 9.75 },
    ])

    const wrapper = await mountView()
    const text = wrapper.get('[data-test="usage-cell"]').text()

    expect(text).toContain('Today$1.25')
    expect(text).toContain('Yesterday$2.50')
    expect(text).toContain('Total$9.75')
    expect(text.indexOf('Today')).toBeLessThan(text.indexOf('Yesterday'))
    expect(text.indexOf('Yesterday')).toBeLessThan(text.indexOf('Total'))
  })

  // Orange 特有：上游成本倍率 / 利润列走 Orange 利润接口
  it('loads group profit data only for the visible profit columns', async () => {
    await mountView()

    expect(getGroupProfits).toHaveBeenCalledTimes(1)
    expect(getGroupProfits).toHaveBeenCalledWith({ ids: [1] })

    // 两个消费利润数据的列都隐藏时不发请求
    localStorage.setItem(
      'group-hidden-columns',
      JSON.stringify(['profit', 'upstream_rate_multiplier']),
    )
    getGroupProfits.mockClear()
    await mountView()
    expect(getGroupProfits).not.toHaveBeenCalled()

    localStorage.clear()
    getGroupProfits.mockClear()
    const toggled = await mountView()
    expect(getGroupProfits).toHaveBeenCalledTimes(1)
    await openColumnSettings(toggled)
    await clickColumnToggle(toggled, 'Profit')
    await clickColumnToggle(toggled, 'Upstream Multiplier')
    // 隐藏列不触发请求；重新显示时补拉
    expect(getGroupProfits).toHaveBeenCalledTimes(1)
    await clickColumnToggle(toggled, 'Profit')
    expect(getGroupProfits).toHaveBeenCalledTimes(2)
  })

  it('renders upstream rate and profit columns from the Orange profit API', async () => {
    getGroupProfits.mockResolvedValue({
      items: [
        {
          group_id: 1,
          upstream_rate_multiplier: 0.8,
          today_revenue: 10,
          today_upstream_price: 5,
          today_upstream_cost: 4,
          today_profit: 6,
          yesterday_revenue: 4,
          yesterday_upstream_price: 2,
          yesterday_upstream_cost: 1.6,
          yesterday_profit: 2.4,
          total_revenue: 100,
          total_upstream_price: 50,
          total_upstream_cost: 40,
          total_profit: -12,
        },
      ],
      generated_at: '2026-01-01T00:00:00Z',
      cached: false,
    })

    const wrapper = await mountView()

    expect(wrapper.get('[data-test="upstream-rate-cell"]').text()).toBe('0.8x')
    const profitText = wrapper.get('[data-test="profit-cell"]').text()
    expect(profitText).toContain('Profit today$6.00')
    expect(profitText).toContain('Profit yesterday$2.40')
    expect(profitText).toContain('Profit total-$12.00')
  })

  it('falls back to 1.0x when a group has no upstream rate record', async () => {
    getGroupProfits.mockResolvedValue({ items: [], generated_at: '', cached: false })

    const wrapper = await mountView()

    expect(wrapper.get('[data-test="upstream-rate-cell"]').text()).toBe('1.0x')
    expect(wrapper.get('[data-test="profit-cell"]').text()).toContain('Profit today$0.00')
  })
})
